/**
 * Vérifie qu'un code 2-lettres est un code pays ISO 3166-1 alpha-2 connu.
 *
 * @param code chaîne ASCII en majuscules.
 * @returns `true` si le code est dans la liste.
 */
export function isIso3166Alpha2(code: string): boolean {
  return ISO_3166_ALPHA2.has(code);
}
